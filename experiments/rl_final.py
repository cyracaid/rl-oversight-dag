#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Final table and figures, built only from generated results (no hand-typed numbers).

Inputs
  spike_active_selection.py   heuristics on seeds 1-20 (recomputed here, seconds)
  methods_compare.json        rl_methods_compare.py  (MLP REINFORCE / PPO / DQN)
  cmdp_result.json            rl_cmdp_gnn.py         (naive CMDP)
  gnn_results.json            rl_gnn_multiseed.py    (GNN static / observed, held-out)
Outputs
  final_table.md, results_bar.png, learning_curves.png
"""
import json
import os
import random

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

import spike_active_selection as SP

OUT = os.path.dirname(os.path.abspath(__file__))


def load(name):
    with open(os.path.join(OUT, name)) as f:
        return json.load(f)


def legacy_heuristics():
    labels = ["No review", "Conf threshold", "Structural greedy",
              "Belief greedy (adaptive, deployable)", "Oracle greedy (reads truth)"]
    agg = [0.0] * len(labels)
    for seed in SP.CFG["seeds"]:
        for k, v in enumerate(SP.run_seed(random.Random(seed), belief_seed=10_000 + seed)):
            agg[k] += v
    return {lab: a / len(SP.CFG["seeds"]) for lab, a in zip(labels, agg)}


def main():
    mc, cmdp, gnn = load("methods_compare.json"), load("cmdp_result.json"), load("gnn_results.json")
    heur = legacy_heuristics()
    cfg = gnn["config"]

    legacy = [(k, f"{v:.2f}") for k, v in heur.items()]
    legacy[4:4] = [(k, f"{v:.2f}") for k, v in mc["results"].items()]
    legacy.insert(-1, ("CMDP soft budget (naive)", f"{cmdp['sink_errors']:.2f}"))
    for v in ("static", "observed"):
        g = gnn["gnn"][v]
        legacy.insert(-1, (f"GNN + REINFORCE ({v} state)",
                           f"{g['legacy_mean']:.2f} ± {g['legacy_ci95']:.2f}"))

    held = [(k, b["heldout_mean"], b["heldout_ci95"]) for k, b in gnn["baselines"].items()]
    held += [(f"GNN ({v} state)", gnn["gnn"][v]["heldout_mean"], gnn["gnn"][v]["heldout_ci95"])
             for v in ("static", "observed")]

    lines = ["# Final results (generated by rl_final.py; do not edit by hand)", "",
             f"## Held-out, paired (main comparison): N={cfg['N']}, budget={cfg['budget']}, "
             f"graphs {cfg['heldout_seeds'][0]}..{cfg['heldout_seeds'][1]}", "",
             "| Policy | Sink errors | 95% CI |", "|---|---:|---:|"]
    lines += [f"| {k} | {m:.2f} | ± {ci:.2f} |" for k, m, ci in held]
    lines += ["", "GNN CI is across training seeds; baseline CI is across graphs.", "",
              "Paired differences (negative = left side better):", ""]
    lines += [f"- {k}: {d['mean']:+.2f} ± {d['ci95']:.2f}" for k, d in gnn["paired"].items()]
    lines += ["", "## Legacy seeds 1-20 (every earlier table used these graphs; easier than "
              "average, sequential rng, not paired)", "",
              "| Method | Sink errors |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in legacy]
    with open(os.path.join(OUT, "final_table.md"), "w") as f:
        f.write("\n".join(lines) + "\n")

    # results bar: held-out, paired, with CIs
    names = [h[0] for h in held]
    colors = ["#bbbbbb", "#999999", "#1a9850", "#2a7de1", "#7fb3f0"]
    plt.figure(figsize=(9, 4.8))
    bars = plt.bar(names, [h[1] for h in held], yerr=[h[2] for h in held], capsize=4,
                   color=colors[: len(held)])
    for b, (_, m, _) in zip(bars, held):
        plt.text(b.get_x() + b.get_width() / 2, 0.05, f"{m:.2f}", ha="center",
                 va="bottom", fontsize=9, color="white", fontweight="bold")
    plt.ylabel("avg sink errors (lower = better)")
    plt.title(f"Held-out graphs (n={cfg['heldout_seeds'][1] - cfg['heldout_seeds'][0] + 1}), "
              "paired, 95% CI")
    plt.xticks(rotation=15, ha="right")
    plt.tight_layout()
    plt.savefig(os.path.join(OUT, "results_bar.png"), dpi=130)
    plt.close()

    # learning curves: real training logs only
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    for v, c in (("static", "#2a7de1"), ("observed", "#1a9850")):
        curves = gnn["gnn"][v]["curves"]
        xs = [p[0] for p in curves[0]]
        ys = [[p[1] for p in cv] for cv in curves]
        mean = [sum(col) / len(col) for col in zip(*ys)]
        axes[0].plot(xs, mean, color=c, label=f"GNN {v} state (mean of {len(ys)} seeds)")
        axes[0].fill_between(xs, [min(col) for col in zip(*ys)],
                             [max(col) for col in zip(*ys)], color=c, alpha=0.15)
    axes[0].axhline(gnn["baselines"]["belief greedy"]["heldout_mean"], color="#555555",
                    ls="--", lw=1, label="belief greedy (held-out)")
    axes[0].set_xlabel("episode")
    axes[0].set_ylabel(f"training sink errors, {cfg['curve_every']}-episode mean")
    axes[0].set_title("GNN + REINFORCE training")
    axes[0].legend(fontsize=8); axes[0].grid(alpha=0.3)
    for name in ("REINFORCE (MLP)", "PPO (MLP)"):
        h = mc["curves"][name]
        axes[1].plot([p[0] for p in h], [-p[1] for p in h], label=name)
    axes[1].set_xlabel("episode")
    axes[1].set_ylabel("training sink errors (EMA of -reward)")
    axes[1].set_title("MLP scorers, static state")
    axes[1].legend(fontsize=8); axes[1].grid(alpha=0.3)
    plt.tight_layout()
    plt.savefig(os.path.join(OUT, "learning_curves.png"), dpi=130)
    plt.close()

    print("\n".join(lines))
    print("\nwrote final_table.md, results_bar.png, learning_curves.png")


if __name__ == "__main__":
    main()
