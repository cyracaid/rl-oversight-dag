"""Generate the mock export (no SciForge data, no ticket data, no sleep rows).

Writes ``sciforge_mock_v1.json`` in the schema of ``triage_bench/SCIFORGE_ASK.md``
§4, using the N=21 sleep-pipeline topology only as a *shape*: node names, types
and the declared conclusions are copied; every error, verdict and duration is
generated here and marked ``synthetic``.

Purpose: exercise the loader, the policy interface and the evaluation protocol
before a real export exists. It is not a dataset and carries no evidence.
"""

from __future__ import annotations

import json
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

from experiments.real_pipeline_graph import LAYER, NAME, PARENTS
from .bench import FALLBACK_PRIOR, TYPE_PRIOR

HERE = Path(__file__).resolve().parent
OUT = HERE / "sciforge_mock_v1.json"
SEED = 20261124
# Layered vocabulary: leaves are raw data, mid layers are runs and figures,
# terminal layer is a claim.
TYPE_BY_LAYER = {0: "dataset", 1: "run", 2: "figure", 3: "claim"}


def build(seed: int = SEED) -> dict:
    rng = random.Random(seed)
    children = {name: [] for name in NAME}
    for child, parents in PARENTS.items():
        for parent in parents:
            children[parent].append(child)

    t0 = datetime(2026, 11, 20, 9, 0, tzinfo=timezone.utc)
    nodes = []
    for i, name in enumerate(NAME):
        nodes.append({
            "id": name,
            "type": TYPE_BY_LAYER[LAYER[i]],
            "is_sink": not children[name],
            "created_at": (t0 + timedelta(minutes=7 * i)).isoformat().replace("+00:00", "Z"),
        })

    edges = [{"src": parent, "dst": child, "rel": "derived_from"}
             for child, parents in PARENTS.items() for parent in parents]
    # Two non-propagation links, so the loader is exercised on every relation.
    edges.append({"src": "TST", "dst": "SE_conclusion", "rel": "supports"})
    edges.append({"src": "TIB", "dst": "SE_conclusion", "rel": "supports"})

    # Errors are drawn from the *declared role prior* (bench.TYPE_PRIOR), not from
    # the sleep type rates: the mock is a positive control for the harness, so the
    # signal it contains has to be the signal the protocol claims to look for.
    role = [TYPE_BY_LAYER[l] for l in LAYER]
    corrections = []
    for i, name in enumerate(NAME):
        if rng.random() < TYPE_PRIOR.get(role[i], FALLBACK_PRIOR):
            corrections.append({
                "node_id": name,
                "error_type": role[i],
                "severity": rng.choice(["low", "medium", "high"]),
                "agreed_by": rng.choice([1, 2, 2, 3]),
            })

    corrected = {c["node_id"] for c in corrections}
    review_order = list(NAME)[:12]
    receipts = []
    stamp = t0 + timedelta(hours=3)
    for i, name in enumerate(review_order):
        stamp += timedelta(minutes=rng.randint(3, 15))
        receipts.append({
            "node_id": name,
            "reviewer_hash": f"r{rng.randint(1, 3)}",
            "reviewed_at": stamp.isoformat().replace("+00:00", "Z"),
            "duration_min": rng.randint(4, 18),
            "verdict": "corrected" if name in corrected else "accepted",
            "synthetic": True,
        })

    return {
        "project": "proj_mock_sleep21",
        "snapshot_at": "2026-11-20T12:00:00Z",
        "synthetic": True,
        "provenance": (
            "Generated by sciforge_review/export/make_mock.py, seed 20261124. "
            "Topology copied from the N=21 sleep pipeline as a shape only. "
            "No SciForge export, no sleep records, no tickets were read. "
            "Source errors are drawn from the declared role prior in bench.TYPE_PRIOR, "
            "so this file is a positive control, not an estimate of anything."
        ),
        "nodes": nodes,
        "edges": edges,
        "corrections": corrections,
        "receipts": receipts,
    }


def main() -> None:
    payload = build()
    OUT.write_text(json.dumps(payload, indent=2, sort_keys=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE.parent.parent)}")
    print(f"nodes={len(payload['nodes'])} edges={len(payload['edges'])} "
          f"corrections={len(payload['corrections'])} receipts={len(payload['receipts'])}")


if __name__ == "__main__":
    main()
