#!/usr/bin/env python3
"""M4-only positive mining: is there any signal above 0.8% precision?

Usage:
    python3 triage_bench/run_m4_mining.py [--data-dir ~/Documents/splsleep]

Grouped CV by participant, permutation test on AUC, top-k precision at the
budgets a curator could afford. Aggregate outputs only.
"""

from __future__ import annotations

import warnings

warnings.filterwarnings("ignore", message="Unknown solver options")

import argparse
import json

import numpy as np

from bench import config
from bench.load import load_queue
from bench.mine_m4 import (build_features, cv_scores, permutation_p,
                           single_feature_auc, topk_precision, univariate_perm_p,
                           _safe_auc)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", default=None)
    parser.add_argument("--perm", type=int, default=200)
    args = parser.parse_args()

    if args.data_dir:
        import os
        os.environ[config.DATA_DIR_ENV] = args.data_dir

    data = config.require_data()
    queue = load_queue(data)
    X, y, groups, features = build_features(queue)
    base = float(y.mean())

    print(f"M4-only block: {len(y)} candidates, {int(y.sum())} positives, base precision {base:.2%}")
    print(f"features: {len(features)}")

    scores = cv_scores(X, y, groups)
    auc = _safe_auc(y, scores)
    p = permutation_p(X, y, groups, auc, n_perm=args.perm)
    topk = topk_precision(scores, y)

    singles = single_feature_auc(X, y)
    p_uni = univariate_perm_p(X, y, float(singles["auc"].max()), n_perm=args.perm)
    print(f"CV AUC {auc:.3f} (perm p={p:.3f}); " + "  ".join(f"{k}={v:.2%}" for k, v in topk.items()))
    print(f"best single-feature AUC {singles['auc'].max():.3f} (family-wise p={p_uni:.3f})")
    print(singles.head(5).to_string(index=False))

    # A fixed univariate rule needs no training, so it cannot overfit: test it as-is.
    uni = []
    for feat in singles["feature"].head(5):
        direction = float(np.sign(singles.loc[singles.feature == feat, "direction"].map({"+": 1, "-": -1}).iloc[0]))
        pks = topk_precision(direction * X[feat].to_numpy(), y)
        uni.append({"feature": feat, **{k: round(v, 6) for k, v in pks.items()}})
        print(f"univariate {feat:24s} " + "  ".join(f"{k}={v:.1%}" for k, v in pks.items()))

    result = {
        "n_candidates": int(len(y)),
        "n_positives": int(y.sum()),
        "base_precision": round(base, 6),
        "n_features": len(features),
        "cv_auc": round(auc, 4),
        "perm_p": round(p, 4),
        "best_single_auc": round(float(singles["auc"].max()), 4),
        "univariate_perm_p": round(p_uni, 4),
        "topk": {k: round(v, 6) for k, v in topk.items()},
        "univariate": uni,
    }
    config.OUT_DIR.mkdir(parents=True, exist_ok=True)
    (config.OUT_DIR / "m4_mining.json").write_text(json.dumps(result, indent=2) + "\n")

    lines = [
        "# M4-only mining - is the remaining headroom real?",
        "",
        f"Candidates: **{len(y)}** M4-only flags  |  positives: **{int(y.sum())}**  "
        f"|  base precision: **{base:.2%}**",
        "",
        "| metric | value |",
        "|---|---:|",
        f"| participant-grouped CV AUC | **{auc:.3f}** |",
        f"| permutation p (AUC) | {p:.3f} |",
        f"| best single-feature AUC | {singles['auc'].max():.3f} (family-wise p={p_uni:.3f}) |",
    ]
    for k, v in topk.items():
        lines.append(f"| precision@{k} | {v:.2%} |")
    lines += [
        "",
        "## Top single features (direction-normalised AUC)",
        "",
        "| feature | AUC | direction |",
        "|---|---:|---|",
    ]
    for _, row in singles.head(10).iterrows():
        lines.append(f"| `{row['feature']}` | {row['auc']:.3f} | {row['direction']} |")
    lines += [
        "",
        "## Fixed univariate rules (no training, so no overfitting)",
        "",
        "| feature | P@10 | P@25 | P@50 | P@100 |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in uni:
        lines.append(
            f"| `{row['feature']}` | {row['p@10']:.1%} | {row['p@25']:.1%} "
            f"| {row['p@50']:.1%} | {row['p@100']:.1%} |"
        )
    lines += [
        "",
        "Grouped CV: a participant never appears in train and test. "
        "Permutation test: 200 label shuffles, same CV. "
        "Generated by `triage_bench/run_m4_mining.py`; do not hand-edit.",
    ]
    (config.OUT_DIR / "m4_mining.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
