#!/usr/bin/env python3
"""Belief greedy inside the M4-only block: does adaptivity beat 1.24%?"""

from __future__ import annotations

import json

from bench import config
from bench.belief_queue import run
from bench.load import load_queue, load_rows
from bench.participant import build_features


def main() -> None:
    data = config.require_data()
    queue = load_queue(data)
    rows = load_rows(data)
    feats = build_features(queue, rows)

    res = run(queue, feats)
    (config.OUT_DIR / "belief_queue.json").write_text(json.dumps(res, indent=2) + "\n")

    ks = (10, 25, 50, 100, 200)
    lines = [
        "# Belief greedy inside the M4-only block",
        "",
        f"{res['n']} candidates, {res['positives']} positives, base precision "
        f"**{res['base_precision']:.2%}**, budget {res['budget']}.",
        "",
        "Simulated deployment: a review reveals the verdict, the prior comes from",
        "M1 density without the participant itself. Not offline policy evaluation.",
        "",
        "| policy | " + " | ".join(f"P@{k}" for k in ks) + " |",
        "|---|" + "---:|" * len(ks),
    ]
    for name, curve in res["variants"].items():
        lines.append(f"| {name} | " + " | ".join(f"{curve[f'p@{k}']:.1%}" for k in ks) + " |")
    lines += [
        "",
        "| policy | " + " | ".join(f"hits@{k}" for k in ks) + " |",
        "|---|" + "---:|" * len(ks),
    ]
    for name, curve in res["variants"].items():
        lines.append(f"| {name} | " + " | ".join(f"{curve[f'hits@{k}']}" for k in ks) + " |")
    lines += [
        "",
        "Numbers generated by `triage_bench/run_belief_queue.py`; do not hand-edit.",
    ]
    (config.OUT_DIR / "belief_queue.md").write_text("\n".join(lines) + "\n")
    print(json.dumps({k: v for k, v in res.items() if k != "variants"}, indent=2))
    for name, curve in res["variants"].items():
        print(f"{name:24s} " + " ".join(f"P@{k}={curve[f'p@{k}']:.1%}" for k in ks))


if __name__ == "__main__":
    main()
